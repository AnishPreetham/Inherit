"""Evidence-linked documentation.

The model writes behavior claims from recorded observations only. A mechanical validator
then checks every "observed" claim cites evidence that exists and was recorded for that
function; claims that fail are downgraded to "inferred". The validator checks provenance,
not truth: a claim can cite the right run and still overgeneralise, so the docs say so.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Literal

from pydantic import BaseModel, Field

from ..evidence import EvidenceStore
from ..llm import LLMClient, LLMError
from .characterize import CharacterizationResult, FunctionInfo, PinnedCase, _call_expr

SYSTEM_PROMPT = (
    "You document Python functions using ONLY recorded observations of real calls. "
    "Reply with ONLY a JSON object: "
    '{"summary": "<one sentence>", "claims": [{"text": "...", "kind": "observed" | "inferred", '
    '"evidence_ids": ["E-0001"]}]}. '
    "An 'observed' claim states what happened for specific recorded inputs and must cite the "
    "evidence IDs given for those observations. Anything broader (a general rule, intent, "
    "likely bugs) is 'inferred' and may cite nothing. Never invent evidence IDs."
)


class Claim(BaseModel):
    text: str
    kind: Literal["observed", "inferred"]
    evidence_ids: list[str] = Field(default_factory=list)


class FunctionDoc(BaseModel):
    summary: str = ""
    claims: list[Claim] = Field(default_factory=list)


@dataclass
class DocEntry:
    function: FunctionInfo
    summary: str
    claims: list[Claim]
    downgraded: list[str] = field(default_factory=list)
    examples: list[PinnedCase] = field(default_factory=list)
    error: str = ""


def describe_case(p: PinnedCase) -> str:
    call = _call_expr(p)[len(p.function.module) + 1:]
    if p.outcome["status"] == "returned":
        out = f"{call} returned {p.outcome['repr']}"
    else:
        out = f"{call} raised {p.outcome['exc_type']}({p.outcome.get('exc_message', '')!r})"
    if p.mutated:
        out += f" and changed module state: {', '.join(p.mutated)}"
    return out


def validate_claims(
    store: EvidenceStore, fn: FunctionInfo, claims: list[Claim], allowed: set[str]
) -> tuple[list[Claim], list[str]]:
    """Downgrade observed claims whose citations are missing, unknown, or for another function."""
    checked, downgraded = [], []
    for c in claims:
        if c.kind == "observed":
            problem = ""
            if not c.evidence_ids:
                problem = "cites no evidence"
            for eid in c.evidence_ids:
                if not store.execution_exists(eid):
                    problem = f"cites nonexistent evidence {eid}"
                elif eid not in allowed:
                    meta = store.execution_meta(eid)
                    if (meta.get("module"), meta.get("function")) != (fn.module, fn.name):
                        problem = f"cites evidence {eid} recorded for a different function"
            if problem:
                downgraded.append(f"{c.text} ({problem})")
                c = Claim(text=c.text, kind="inferred", evidence_ids=[])
        else:
            c = Claim(text=c.text, kind="inferred", evidence_ids=[])
        checked.append(c)
    return checked, downgraded


def document_function(
    llm: LLMClient, store: EvidenceStore, fn: FunctionInfo, examples: list[PinnedCase]
) -> DocEntry:
    allowed = {e for p in examples for e in p.evidence_ids}
    observations = "\n".join(f"- {describe_case(p)} [evidence: {', '.join(p.evidence_ids)}]" for p in examples)
    prompt = (
        f"Function: {fn.qualified}\nSignature: {fn.signature}\nSource:\n{fn.source}\n\n"
        f"Recorded observations:\n{observations or '(none)'}"
    )
    entry = DocEntry(fn, "", [], examples=examples)
    try:
        doc = llm.complete_json("reasoner", SYSTEM_PROMPT, prompt, FunctionDoc, task=f"docs:{fn.qualified}")
    except LLMError as exc:
        entry.error = str(exc)
        doc = FunctionDoc()
    entry.summary = doc.summary
    entry.claims, entry.downgraded = validate_claims(store, fn, doc.claims, allowed)
    for c in entry.claims:
        store.add_claim(c.text, c.kind, fn.qualified, c.evidence_ids)
    return entry


def document(llm: LLMClient, store: EvidenceStore, char: CharacterizationResult) -> list[DocEntry]:
    by_fn: dict[str, list[PinnedCase]] = {}
    for p in char.pinned:
        by_fn.setdefault(p.function.qualified, []).append(p)
    return [document_function(llm, store, fn, by_fn.get(fn.qualified, [])) for fn in char.functions]


def _cite(ids: list[str]) -> str:
    return " ".join(f"[{e}](report.html#{e})" for e in ids)


def render_docs(entries: list[DocEntry]) -> str:
    out = [
        "# Behavior documentation (generated by Inherit)",
        "",
        "**Observed** statements cite the recorded runs that support them; Inherit checked each "
        "citation exists and belongs to that function. That check is about provenance, not truth: "
        "an observed statement covers only the inputs that were run. **Inferred** statements are "
        "the model's interpretation and were not verified.",
        "",
    ]
    for e in entries:
        out += [f"## `{e.function.qualified}`", "", f"`{e.function.signature}`", ""]
        if e.summary:
            out += [f"{e.summary} *(inferred)*", ""]
        observed = [c for c in e.claims if c.kind == "observed"]
        inferred = [c for c in e.claims if c.kind == "inferred"]
        if observed:
            out += ["**Observed**", ""] + [f"- {c.text} {_cite(c.evidence_ids)}" for c in observed] + [""]
        if inferred:
            out += ["**Inferred (unverified)**", ""] + [f"- {c.text}" for c in inferred] + [""]
        if e.examples:
            out += ["**Recorded calls**", ""]
            for p in e.examples:
                flag = " ⚠ review" if p.flagged else ""
                out.append(f"- `{describe_case(p)}`{flag} {_cite(p.evidence_ids)}")
            out.append("")
        else:
            out += ["*No behavior was recorded for this function.*", ""]
        if e.downgraded:
            out += ["*Claims downgraded by the validator:* " + "; ".join(e.downgraded), ""]
        if e.error:
            out += [f"*Documentation failed: {e.error}*", ""]
    return "\n".join(out)
